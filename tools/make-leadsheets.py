#!/usr/bin/env python3
"""由 tools/leadsheets.json 產生 sample 用嘅 lead sheet（五線譜＋和弦＋旋律，SVG）。

旋律係按和弦走位用固定 seed 生成嘅「示範譜」，唔係歌曲真實旋律；用家上載自己嘅譜取代。
用法：python3 tools/make-leadsheets.py            （輸出 media/charts/<slug>-lead.svg）
"""
import json, random
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SPEC = json.loads((ROOT / 'tools' / 'leadsheets.json').read_text(encoding='utf-8'))

LETTERS = 'CDEFGAB'
NAT = [0, 2, 4, 5, 7, 9, 11]                       # 每個字母嘅自然半音
SHARPS, FLATS = 'FCGDAEB', 'BEADGCF'
# 和弦成員：(字母步數, 半音)
QUAL = {
    'maj7': [(0, 0), (2, 4), (4, 7), (6, 11)], 'm7': [(0, 0), (2, 3), (4, 7), (6, 10)],
    '7': [(0, 0), (2, 4), (4, 7), (6, 10)], 'm7b5': [(0, 0), (2, 3), (4, 6), (6, 10)],
    'm': [(0, 0), (2, 3), (4, 7)], '': [(0, 0), (2, 4), (4, 7)], '7sus': [(0, 0), (3, 5), (4, 7), (6, 10)],
}


def parse_chord(sym):
    li = LETTERS.index(sym[0]); alt = 0; i = 1
    while i < len(sym) and sym[i] in '#b':
        alt += 1 if sym[i] == '#' else -1; i += 1
    q = sym[i:]
    if q not in QUAL:
        raise SystemExit(f'唔識和弦品質：{sym}')
    root_semi = (NAT[li] + alt) % 12
    tones = []
    for step, semi in QUAL[q]:
        l = (li + step) % 7
        a = ((root_semi + semi - NAT[l] + 6) % 12) - 6
        tones.append((l, a))
    return {'sym': sym, 'root': (li, alt), 'tones': tones}


def key_alters(n):
    alt = {l: 0 for l in range(7)}
    for k in range(abs(n)):
        alt[LETTERS.index((SHARPS if n > 0 else FLATS)[k])] = 1 if n > 0 else -1
    return alt


RHY = {4: [[1, 1, 1, 1], [1.5, .5, 1, 1], [2, 1, 1], [1, 1, 2], [.5, .5, 1, 2], [1, .5, .5, 2], [2, 2], [1.5, .5, 2], [1, 1, .5, .5, 1]],
       3: [[1, 1, 1], [2, 1], [1, 2], [1.5, .5, 1], [1, .5, .5, 1]]}


def compose(prog, keysig, beats, seed):
    rnd = random.Random(seed); kal = key_alters(keysig)
    lo, hi = 30, 38                                   # D4..A5（pos＝八度×7＋字母）
    cur = 34 + rnd.choice([0, 1, 2])
    bars = []
    for bi, chords in enumerate(prog):
        last = bi == len(prog) - 1
        notes, t = [], 0.0
        pats = [[beats]] if last else RHY[beats]
        pat = rnd.choice(pats)
        for d in pat:
            sym = chords[-1][0] if (len(chords) > 1 and t >= chords[1][1]) else chords[0][0]
            ch = parse_chord(sym)
            letters = {l: a for l, a in ch['tones']}
            strong = t == int(t)
            want = cur + (rnd.choice([-2, -1, 1, 2]) if strong else rnd.choice([-1, 1]))
            if last:
                cands = [p for p in range(lo, hi + 1) if p % 7 == ch['root'][0]]
            elif strong:
                cands = [p for p in range(lo, hi + 1) if (p % 7) in letters]
            else:
                cands = list(range(lo, hi + 1))
            p = min(cands, key=lambda c: (abs(c - want), rnd.random()))
            alter = letters.get(p % 7, kal[p % 7])
            notes.append({'pos': p, 'alter': alter, 'dur': d, 'at': t})
            cur = p; t += d
        bars.append({'chords': chords, 'notes': notes})
    return bars


# ---------------- 繪圖 ----------------
GAP = 8
W, M, CLEF = 960, 36, 64
BARS_PER_SYS = 4
SYS_H = 120


def glyph_acc(a):
    return {-1: '♭', 0: '♮', 1: '♯'}[a]


def chord_label(sym):
    s = sym.replace('maj7', 'maj7').replace('m7b5', 'm7♭5')
    root = s[0]; i = 1
    while i < len(s) and s[i] in '#b':
        root += '♯' if s[i] == '#' else '♭'; i += 1
    return root + s[i:]


def render(song):
    title, keysig, beats, tempo = song['title'], song['keysig'], song['beats'], song['tempo']
    bars = compose(song['prog'], keysig, beats, song.get('seed', 1))
    kal = key_alters(keysig)
    nsys = (len(bars) + BARS_PER_SYS - 1) // BARS_PER_SYS
    H = 110 + nsys * SYS_H + 20
    o = [f'<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 {W} {H}" font-family="Helvetica, Arial, sans-serif">',
         f'<rect width="{W}" height="{H}" fill="#fdfcf9"/>',
         f'<text x="{W/2}" y="34" font-size="24" font-weight="700" text-anchor="middle" fill="#1b1b1d">{title}</text>',
         f'<text x="{M}" y="62" font-size="12" fill="#444">{song["feel"]} · ♩ = {tempo} · {beats}/4 · {song["keyname"]}</text>',
         f'<text x="{W-M}" y="62" font-size="11" text-anchor="end" fill="#888">Sample lead sheet · demo melody generated by Flowboard</text>']
    # 調號每個字母喺高音譜表上嘅位置（以底線 E4＝pos 30 為 0）
    sig_pos = {'F': 38, 'C': 35, 'G': 39, 'D': 36, 'A': 33, 'E': 37, 'B': 34}
    sig_pos_flat = {'B': 34, 'E': 37, 'A': 33, 'D': 36, 'G': 32, 'C': 35, 'F': 31}
    for s in range(nsys):
        top = 122 + s * SYS_H            # 第 5 線（最高線）
        yline = lambda i: top + i * GAP   # i=0 最高線 … 4 最低線
        bottom = yline(4)
        ypos = lambda p: bottom - (p - 30) * GAP / 2     # p=30（E4）喺底線
        for i in range(5):
            o.append(f'<line x1="{M}" y1="{yline(i)}" x2="{W-M}" y2="{yline(i)}" stroke="#333" stroke-width="0.8"/>')
        o.append(f'<line x1="{M}" y1="{top}" x2="{M}" y2="{bottom}" stroke="#333" stroke-width="1.2"/>')
        x0 = M + 6
        o.append(f'<path transform="translate({x0+4} {bottom})" d="M3 10 C3 16 13 16 12 8 L12 -30 C12 -42 8 -50 5 -45 C2 -40 6 -32 14 -26 C24 -18 22 -4 10 -4 C0 -4 -2 -14 6 -17 C13 -20 18 -14 14 -10" fill="none" stroke="#1b1b1d" stroke-width="2.2" stroke-linecap="round"/>')
        x = x0 + 30
        if s == 0:
            order = (SHARPS if keysig > 0 else FLATS)[:abs(keysig)]
            for k, L in enumerate(order):
                p = (sig_pos if keysig > 0 else sig_pos_flat)[L]
                o.append(f'<text x="{x + k*8}" y="{ypos(p)+5}" font-size="15" fill="#1b1b1d">{"♯" if keysig > 0 else "♭"}</text>')
            x += abs(keysig) * 8 + 8
            o.append(f'<text x="{x}" y="{yline(2)-1}" font-size="19" font-weight="700" text-anchor="middle" fill="#1b1b1d">{beats}</text>')
            o.append(f'<text x="{x}" y="{yline(4)-1}" font-size="19" font-weight="700" text-anchor="middle" fill="#1b1b1d">4</text>')
            x += 18
        else:
            x = x0 + 34
        row = bars[s * BARS_PER_SYS:(s + 1) * BARS_PER_SYS]
        bw = (W - M - x) / BARS_PER_SYS
        o.append(f'<text x="{M-4}" y="{top-26}" font-size="10" text-anchor="end" fill="#888">{s*BARS_PER_SYS+1}</text>')
        for bi, bar in enumerate(row):
            bx = x + bi * bw
            idx = s * BARS_PER_SYS + bi
            if idx % 8 == 0 and song.get('letters'):
                letter = chr(65 + idx // 8)
                o.append(f'<rect x="{bx+2}" y="{top-42}" width="16" height="16" fill="none" stroke="#1b1b1d" stroke-width="1.2"/><text x="{bx+10}" y="{top-30}" font-size="12" font-weight="700" text-anchor="middle" fill="#1b1b1d">{letter}</text>')
            last = idx == len(bars) - 1
            ex = bx + bw
            o.append(f'<line x1="{ex}" y1="{top}" x2="{ex}" y2="{bottom}" stroke="#333" stroke-width="{1 if not last else 1}"/>')
            if last:
                o.append(f'<line x1="{ex+4}" y1="{top}" x2="{ex+4}" y2="{bottom}" stroke="#333" stroke-width="3"/>')
            for sym, beat in bar['chords']:
                cx = bx + 10 + (beat / beats) * (bw - 20)
                o.append(f'<text x="{cx}" y="{top-8}" font-size="14" font-weight="700" fill="#b0402a">{chord_label(sym)}</text>')
            memory = {}
            pad = 14
            nx = lambda t: bx + pad + 6 + (t / beats) * (bw - 2 * pad - 10)
            xs = [nx(n['at']) for n in bar['notes']]
            # 配對 beam：同一拍入面嘅兩個八分音符
            beamed = {}
            for i, n in enumerate(bar['notes'][:-1]):
                m = bar['notes'][i + 1]
                if n['dur'] == .5 and m['dur'] == .5 and n['at'] == int(n['at']) and i not in beamed:
                    beamed[i] = i + 1; beamed[i + 1] = i
            drawn = set()
            for i, n in enumerate(bar['notes']):
                p, a, d = n['pos'], n['alter'], n['dur']
                cx, cy = xs[i], ypos(p)
                key = p
                cur = memory.get(key, kal[p % 7])
                if a != cur:
                    o.append(f'<text x="{cx-14}" y="{cy+5}" font-size="14" fill="#1b1b1d">{glyph_acc(a)}</text>')
                memory[key] = a
                # 加線
                if p <= 28:
                    for lp in range(28, p - 1, -2):
                        ly = ypos(lp); o.append(f'<line x1="{cx-9}" y1="{ly}" x2="{cx+9}" y2="{ly}" stroke="#333" stroke-width="0.9"/>')
                if p >= 40:
                    for lp in range(40, p + 1, 2):
                        ly = ypos(lp); o.append(f'<line x1="{cx-9}" y1="{ly}" x2="{cx+9}" y2="{ly}" stroke="#333" stroke-width="0.9"/>')
                hollow = d >= 2
                o.append(f'<ellipse cx="{cx}" cy="{cy}" rx="5.6" ry="4.2" transform="rotate(-18 {cx} {cy})" fill="{"#fdfcf9" if hollow else "#1b1b1d"}" stroke="#1b1b1d" stroke-width="1.3"/>')
                if d in (1.5, 3):
                    o.append(f'<circle cx="{cx+9}" cy="{cy-2}" r="1.6" fill="#1b1b1d"/>')
                if d < 4:
                    up = p < 34 if i not in beamed else (p + bar['notes'][beamed[i]]['pos']) / 2 < 34
                    sx = cx + 5 if up else cx - 5
                    tip = cy - 28 if up else cy + 28
                    if i in beamed:
                        j = beamed[i]; q = bar['notes'][j]
                        tip = ypos(q['pos']) - 28 if up else ypos(q['pos']) + 28
                        tip_i = cy - 28 if up else cy + 28
                        if i < j:
                            sx2 = (xs[j] + 5) if up else (xs[j] - 5)
                            o.append(f'<line x1="{sx}" y1="{cy}" x2="{sx}" y2="{tip_i}" stroke="#1b1b1d" stroke-width="1.2"/>')
                            o.append(f'<line x1="{sx2}" y1="{ypos(q["pos"])}" x2="{sx2}" y2="{tip}" stroke="#1b1b1d" stroke-width="1.2"/>')
                            o.append(f'<line x1="{sx}" y1="{tip_i}" x2="{sx2}" y2="{tip}" stroke="#1b1b1d" stroke-width="3.2"/>')
                    else:
                        o.append(f'<line x1="{sx}" y1="{cy}" x2="{sx}" y2="{tip}" stroke="#1b1b1d" stroke-width="1.2"/>')
                        if d <= .5:
                            dy = 1 if up else -1
                            o.append(f'<path d="M{sx} {tip} c 2 {8*dy} 9 {8*dy} 7 {16*dy}" fill="none" stroke="#1b1b1d" stroke-width="1.8"/>')
    o.append('</svg>')
    return '\n'.join(o)


def main():
    out = ROOT / 'media' / 'charts'
    out.mkdir(parents=True, exist_ok=True)
    for song in SPEC['songs']:
        path = out / f'{song["slug"]}-lead.svg'
        prog = [[(c, 0.0)] if isinstance(c, str) else [(c[0], 0.0), (c[1], song['beats'] / 2)] for c in song['bars']]
        song = {**song, 'prog': prog}
        path.write_text(render(song), encoding='utf-8')
        print('wrote', path.relative_to(ROOT))


if __name__ == '__main__':
    main()
